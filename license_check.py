"""
Проверка лицензии - работает до 30 марта 2026.
После этой даты программа выдаёт случайные ошибки.
"""
import random
import base64
from datetime import datetime


# Зашифрованная дата окончания (base64): "2026-03-30"
_EXPIRY_ENC = "MjAyNi0wMy0zMA=="

def _get_expiry():
    """Расшифровывает дату окончания."""
    try:
        date_str = base64.b64decode(_EXPIRY_ENC).decode('utf-8')
        year, month, day = map(int, date_str.split('-'))
        return datetime(year, month, day, 23, 59, 59)
    except:
        # Если расшифровка не удалась - считаем что лицензия истекла
        return datetime(2020, 1, 1)


def check_license():
    """Проверяет срок действия лицензии. Возвращает True если всё ок."""
    try:
        now = datetime.now()
        expiry = _get_expiry()
        
        # Дополнительная проверка: если системная дата подозрительно старая
        if now.year < 2026:
            # Проверяем что дата не в прошлом относительно компиляции
            compile_check = datetime(2026, 3, 1)  # Дата компиляции
            if now < compile_check:
                return False  # Дата откручена назад
        
        return now <= expiry
    except:
        return False


def get_random_error():
    """Возвращает случайную ошибку (выглядит как баг программы)."""
    errors = [
        "Ошибка подключения к базе данных",
        "Не удалось инициализировать драйвер",
        "Ошибка парсинга конфигурации",
        "Недостаточно памяти для выполнения операции",
        "Ошибка чтения файла настроек",
        "Не удалось загрузить модуль selenium",
        "Ошибка инициализации GUI компонентов",
        "Критическая ошибка: нарушение целостности данных",
        "Ошибка сетевого подключения",
        "Не удалось запустить Chrome драйвер",
        "Ошибка доступа к файловой системе",
        "Неожиданное завершение процесса",
        "Ошибка импорта зависимостей",
        "Конфликт версий библиотек",
    ]
    return random.choice(errors)


def maybe_fail(operation_name="операция"):
    """
    Если лицензия истекла - с вероятностью 90% выбрасывает исключение.
    Используется в критических местах программы.
    """
    if not check_license():
        if random.random() < 0.9:  # 90% вероятность ошибки
            raise Exception(f"{get_random_error()} ({operation_name})")


def should_work():
    """
    Если лицензия истекла - возвращает False с вероятностью 85%.
    Используется для проверок перед операциями.
    """
    if not check_license():
        return random.random() > 0.85  # 15% шанс что сработает
    return True


# Дополнительная проверка при импорте модуля
if not check_license():
    # Случайная ошибка при импорте (50% вероятность)
    if random.random() < 0.5:
        raise ImportError(f"Ошибка загрузки модуля: {get_random_error()}")
